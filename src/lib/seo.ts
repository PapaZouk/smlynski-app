import type { Metadata } from "next";
import { siteConfig } from "@/content/site";

/** Build an absolute URL on the canonical host for a root-relative path. */
export function absoluteUrl(path: string = "/"): string {
  return new URL(path, siteConfig.siteUrl).toString();
}

/**
 * Stable `@id` of the business entity. The root layout declares it on the
 * LocalBusiness graph; per-page `Service` schema references it as `provider`.
 */
export const businessId = absoluteUrl("/#localbusiness");

/**
 * Default social-share card (1200×630) used by every page that does not
 * pass its own `ogImage`. Generated by `scripts/generate-og-image.mjs`.
 */
export const DEFAULT_OG_IMAGE = "/og-default.jpg";

/** SERP snippet budget for meta descriptions. */
const MAX_DESCRIPTION_LENGTH = 160;

const CITY_LIST = siteConfig.serviceArea.join(", ");
/** Tag for descriptions with no locality signal at all. */
const AREA_TAG = ` — Trójmiasto: ${CITY_LIST}.`;
/** Tag for descriptions that already name the region — adds the cities only. */
const CITY_TAG = ` — ${CITY_LIST}.`;

/** True when the text already names one of the served cities. */
function mentionsCity(text: string): boolean {
  // Covers declensions: "Gdańsku", "Gdyni", "Sopot"/"Sopocie", "Rumi"…
  return /gdańsk|gdyni|sopo[cct]|rumi|wejherow/i.test(text);
}

/**
 * Make a description region-relevant for local searches.
 *
 * Descriptions that already name a served city are returned untouched.
 * Others get the city list appended (plus the "Trójmiasto" label when the
 * region is not mentioned yet), truncated to the snippet budget — long offer
 * summaries would otherwise bury any locality signal past the SERP
 * truncation point.
 */
function descriptionWithArea(description: string): string {
  if (mentionsCity(description)) {
    return description;
  }
  const tag = /trójmi/i.test(description) ? CITY_TAG : AREA_TAG;
  const budget = MAX_DESCRIPTION_LENGTH - tag.length;
  let text = description.trim();
  if (text.length > budget) {
    text = text.slice(0, budget);
    const lastSpace = text.lastIndexOf(" ");
    if (lastSpace > budget * 0.6) {
      text = text.slice(0, lastSpace);
    }
    text = `${text.replace(/[.,;:–—-]+$/u, "").trimEnd()}…`;
  }
  return text + tag;
}

interface PageMetadataInput {
  /** Root-relative path of the page, e.g. "/projects/moj-slug". */
  path: string;
  /** Page title; omit to inherit the layout's default (home page). */
  title?: string;
  description: string;
  /** Optional social-share image path under /public. */
  ogImage?: string;
}

/**
 * Per-page metadata with canonical URL and OpenGraph URL.
 *
 * Every indexable page should use this so canonicals stay consistent with
 * the sitemap (see docs/adr/0017-seo-canonicals.md). It also carries the
 * base OpenGraph fields (`type`/`locale`/`siteName`) that Next.js does not
 * deep-merge from the root layout — without them every subpage would drop
 * `og:type`, `og:locale` and `og:site_name`.
 */
export function pageMetadata({
  path,
  title,
  description,
  ogImage,
}: PageMetadataInput): Metadata {
  const url = absoluteUrl(path);
  const image = absoluteUrl(ogImage ?? DEFAULT_OG_IMAGE);
  const metaDescription = descriptionWithArea(description);
  const isDefaultImage = !ogImage;
  return {
    ...(title ? { title } : {}),
    description: metaDescription,
    alternates: {
      canonical: url,
    },
    openGraph: {
      type: "website",
      locale: "pl_PL",
      siteName: siteConfig.companyName,
      url,
      ...(title ? { title } : {}),
      description: metaDescription,
      images: [
        {
          url: image,
          // Only the generated default card has a known aspect ratio.
          ...(isDefaultImage ? { width: 1200, height: 630 } : {}),
        },
      ],
    },
    twitter: {
      card: "summary_large_image",
      ...(title ? { title } : {}),
      description: metaDescription,
      images: [image],
    },
  };
}
